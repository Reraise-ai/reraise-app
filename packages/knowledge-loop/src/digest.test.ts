import { computeContentHash } from '@worldbuilder/core';
import type { Card, World } from '@worldbuilder/core';
import { describe, expect, it } from 'vitest';
import {
  buildDigest,
  checkDigestPage,
  lineText,
  renderDigestMarkdown,
  worldPageId,
} from './digest.js';
import { ulid } from './test-helpers.js';
import { validateContract } from './validate.js';

const STORE = '45aaff12-777f-40e3-a97c-8a592e1ea4f6';
const W1 = ulid(1, '01JW');
const W2 = ulid(2, '01JW');
const worlds: World[] = [
  { id: W1, name: 'Strait transit' } as World,
  { id: W2, name: 'Fleet' } as World,
];

function card(n: number, fields: Partial<Card>): Card {
  const c = {
    id: ulid(n),
    externalId: ulid(n),
    uri: `wb:${STORE}/${ulid(n)}`,
    format: 2,
    type: 'claim',
    title: `Card ${n}`,
    author: 'human',
    layer: 'said',
    source: 'https://news.example.org/a',
    ...fields,
  } as Card;
  return { ...c, contentHash: computeContentHash(c) };
}

const cards = [
  card(1, { title: 'Wire report on transit restrictions', worlds: [W1], date: '2026-09-01' }),
  card(2, { title: 'Coastal navy', type: 'organisation', worlds: [W1, W2], layer: 'evidenced' }),
  card(3, { title: 'A claim\nacross lines', worlds: [W1] }),
  card(4, { title: 'Loose note', type: 'experience', layer: 'experience', source: undefined }),
  card(5, { title: 'Q4 routing board', type: 'lage', worlds: [W1] }),
];
const options = { generatedAt: '2026-10-06T22:00:00.000Z', target: 'local_model' as const };

describe('buildDigest (ADR-0043)', () => {
  const pages = buildDigest(cards, worlds, options);

  it('builds one page per world, sorted by name, and one for cards without a world', () => {
    expect(pages.map((p) => [p.pageId, p.title])).toEqual([
      [worldPageId(W2), 'Fleet'],
      [worldPageId(W1), 'Strait transit'],
      ['unassigned', 'Cards without a world'],
    ]);
  });

  it('lists every card once per page, sorted by type, then title; Lage cards are left out', () => {
    const strait = pages[1]!;
    expect(strait.lines).toEqual([
      { text: 'A claim across lines (said, claim)', cardIds: [ulid(3)] },
      { text: 'Wire report on transit restrictions (said, claim, 2026-09-01)', cardIds: [ulid(1)] },
      { text: 'Coastal navy (evidenced, organisation)', cardIds: [ulid(2)] },
    ]);
    expect(strait.sources.map((s) => s.cardId)).toEqual([ulid(3), ulid(1), ulid(2)]);
    expect(strait.sources[0]!.contentHash).toBe(cards[2]!.contentHash);
  });

  it('produces pages that satisfy the contract', () => {
    for (const p of pages)
      expect(validateContract('digest-page.schema.json', p)).toEqual({ ok: true });
  });

  it('is deterministic and names unknown worlds by id', () => {
    expect(buildDigest([...cards].reverse(), worlds, options)).toEqual(pages);
    expect(buildDigest(cards, [], options)[0]!.title).toMatch(/^World 01JW/);
  });

  it('writes unclassified for a card without a layer', () => {
    expect(lineText(card(9, { layer: undefined, type: 'topic' }))).toBe(
      'Card 9 (unclassified, topic)',
    );
  });

  it('renders Markdown with a link per card id, by wb: URI', () => {
    const uris = new Map(cards.map((c) => [c.id, c.uri!]));
    const md = renderDigestMarkdown(pages[1]!, (id) => uris.get(id) ?? id);
    expect(md).toContain('<!-- Generated by wb digest');
    expect(md).toContain('# Strait transit');
    expect(md).toContain(
      `- Wire report on transit restrictions (said, claim, 2026-09-01) [${ulid(1)}](<wb:${STORE}/${ulid(1)}>)`,
    );
    expect(md.endsWith('\n')).toBe(true);
    expect(renderDigestMarkdown(pages[2]!)).toContain(`[${ulid(4)}](<${ulid(4)}>)`);
  });
});

describe('checkDigestPage (ADR-0043)', () => {
  const page = buildDigest(cards, worlds, options)[1]!;

  it('is fresh while nothing changed', () => {
    expect(checkDigestPage(page, cards)).toEqual({
      fresh: true,
      changed: [],
      removed: [],
      added: [],
    });
  });

  it('reports changed, removed and added cards', () => {
    const edited = card(1, { title: 'Wire report, corrected', worlds: [W1] });
    const moved = card(3, { title: 'A claim\nacross lines', worlds: [W2] });
    const fresh = card(6, { title: 'New finding', worlds: [W1] });
    const now = [edited, cards[1]!, moved, cards[3]!, fresh];
    expect(checkDigestPage(page, now)).toEqual({
      fresh: false,
      changed: [ulid(1)],
      removed: [ulid(3)],
      added: [ulid(6)],
    });
  });

  it('ignores metadata changes that do not change the content hash', () => {
    const tagged = cards.map((c) => (c.id === ulid(1) ? { ...c, tags: ['watch'] } : c));
    expect(checkDigestPage(page, tagged).fresh).toBe(true);
  });
});
